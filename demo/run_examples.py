#!/usr/bin/env python3
"""Run four realistic examples through the whole Lethe path and record what each party saw.

Writes demo/examples/results.json and demo/examples/RESULTS.md.
Uses the key in demo/.env (dry run without one).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from server import App  # noqa: E402

EXAMPLES = [
    {"id": "health", "title": "A parent asks about medication",
     "turns": ["My son Ethan Miller, 9, has ADHD. Should he switch from Adderall to Vyvanse? We're on Kaiser in "
               "Sacramento and his school wants a 504 plan. Reach me at sarah.miller@gmail.com.",
               "Write a three-sentence note I can hand Ethan's teacher, Mrs. Johnson, about the change."]},
    {"id": "career", "title": "An employee asks about a non-compete",
     "turns": ["I'm a VP at Goldman Sachs in Manhattan. My manager David Chen wants me to sign a 12-month "
               "non-compete before my bonus is paid. Can he make that a condition? My cell is (212) 555-0198."]},
    {"id": "housing", "title": "A tenant asks about a deposit",
     "turns": ["My landlord Robert Kim hasn't returned my $2,400 deposit for 482 Oak Street, Austin, TX 78704. "
               "He still has my SSN 123-45-6789 from the rental application. What are my rights, and what should "
               "I send him?"]},
    {"id": "work", "title": "A founder drafts a confidential email", "hide": "Acme Capital, Project Orion",
     "turns": ["Draft a short email to Jennifer Lopez at Acme Capital saying we need to delay Project Orion's "
               "launch to Q2 because the security audit found two issues. Sign it from Michael."]},
]


def main():
    app = App()
    model = next(iter(app.provider["models"]))
    out = []
    for ex in EXAMPLES:
        app.handle("/api/new_chat", {}, "127.0.0.1")
        turns = []
        for prompt in ex["turns"]:
            res = app.handle("/api/ask", {"prompt": prompt, "hide": ex.get("hide", ""), "model": model}, "127.0.0.1")
            r = res["result"]
            turns.append({"prompt": prompt, "sent": r["scrub"]["text"], "found": r["scrub"]["found"],
                          "scrub_ms": r["scrub"]["ms"], "answer_raw": r.get("answer_raw"),
                          "answer": (r.get("answer") or "").replace("", "").replace("", ""),
                          "restored": r.get("restored"), "timing": r["timing"], "usage": r.get("usage"),
                          "error": r.get("error"), "relay": res["relay"], "gateway_status": res["gateway"]["status"],
                          "lab_body": res["lab"]["body"] if res["lab"] else None})
            print(f"[{ex['id']}] swapped {len(r['scrub']['found'])} in {r['scrub']['ms']} ms · "
                  f"lab {r['timing']['lab_ms']} ms · restored {len(r.get('restored') or [])}"
                  + (f" · ERROR {r['error']}" if r.get("error") else ""), flush=True)
        out.append({**ex, "vault": app.device.scrubber.vault_view(), "turns": turns})
    replay = app.handle("/api/replay", {}, "127.0.0.1")["result"]
    print("[replay]", replay)

    dest = HERE / "examples"
    dest.mkdir(exist_ok=True)
    (dest / "results.json").write_text(json.dumps({"model": app.provider["models"][model], "provider":
                                                   app.provider["name"], "examples": out, "replay": replay}, indent=2))
    md = [f"# Lethe demo: four examples\n\nModel: `{app.provider['models'][model]}` via {app.provider['name']}. "
          "Generated by `run_examples.py`.\n"]
    for ex in out:
        md.append(f"\n## {ex['title']}\n")
        for i, t in enumerate(ex["turns"], 1):
            md.append(f"\n**Turn {i}. You wrote:** {t['prompt']}\n\n**The lab received:** {t['sent']}\n\n"
                      f"**Swapped on device ({t['scrub_ms']} ms):** "
                      + "; ".join(f"{f['original']} → {f['standin']}" for f in t["found"]) + "\n")
            if t["error"]:
                md.append(f"\n**Error:** {t['error']}\n")
            else:
                md.append(f"\n**Answer, names restored on device:**\n\n> " + t["answer"].replace("\n", "\n> ") + "\n")
    md.append(f"\n## Replay\n\nRe-sending the last sealed request: {replay.get('error')}\n")
    (dest / "RESULTS.md").write_text("".join(md))
    print("wrote", dest / "results.json")


if __name__ == "__main__":
    main()
